const {spawn, spawnSync} = require('node:child_process');
const fs = require('node:fs');
const path = require('node:path');
const readline = require('node:readline');
const assert = require('node:assert/strict');
// Keep the live AGY evidence untouched; each run resets a separate synthetic fixture.
const base = path.join(__dirname, 'verification-fixture');
fs.mkdirSync(base, {recursive:true});
fs.copyFileSync(path.join(__dirname, 'server.js'), path.join(base, 'server.js'));
fs.writeFileSync(path.join(base, 'data.json'), JSON.stringify({projects:{alpha:{memory:'alpha-base:alpha-note',revision:1},beta:{memory:'beta-base:',revision:0}},drafts:[],nextId:3},null,2));
const load = () => JSON.parse(fs.readFileSync(path.join(base,'data.json'),'utf8'));
const child = spawn(process.execPath,[path.join(base,'server.js'),'alpha'],{stdio:['pipe','pipe','inherit']});
const lines = readline.createInterface({input:child.stdout});
const pending = new Map();
let id = 0;
lines.on('line', line => { const result=JSON.parse(line); const resolve=pending.get(result.id); if(resolve) { pending.delete(result.id); resolve(result); } });
const call = (method, params) => new Promise(resolve => {const current=++id; pending.set(current,resolve); child.stdin.write(JSON.stringify({jsonrpc:'2.0',id:current,method,params})+'\n');});
const tool = (name, args={}) => call('tools/call',{name,arguments:args});
const approve = n => spawnSync(process.execPath,[path.join(base,'server.js'),'approve',String(n)],{encoding:'utf8'});
(async()=>{
  const before = load();
  assert.equal(before.projects.alpha.memory,'alpha-base:alpha-note');
  assert.equal(before.projects.beta.memory,'beta-base:');
  assert.equal(before.drafts.length,0);
  assert.ok((await tool('read_memory',{project:'beta'})).error);
  assert.ok((await tool('propose_memory',{project:'beta',text:'x'})).error);
  assert.ok((await tool('approve_memory',{id:99})).error);
  assert.ok((await tool('propose_memory',{text:'x'.repeat(101)})).error);
  assert.ok((await tool('propose_memory',{text:'first'})).result);
  assert.ok((await tool('propose_memory',{text:'second'})).result);
  const [first,second]=load().drafts;
  assert.equal(approve(first.id).status,0);
  assert.notEqual(approve(second.id).status,0);
  const after=load();
  assert.equal(after.projects.alpha.memory,'alpha-base:alpha-notefirst');
  assert.equal(after.projects.beta.memory,'beta-base:');
  assert.equal(after.drafts.length,1);
  console.log('PASS: isolated fixture rejects cross-project arguments, MCP approval, oversized drafts, and stale approvals; verified alpha/beta persistence');
})().catch(error=>{console.error(error);process.exitCode=1;}).finally(()=>{child.stdin.end();});
